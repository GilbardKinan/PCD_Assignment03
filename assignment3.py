def load_and_preprocess(sample_info, target_size=280):
    """Loads image, converts to grayscale manually, and applies center cropping."""
    filepath = sample_info["file"]
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"File '{filepath}' not found.")

    img_array = np.array(Image.open(filepath))

    # Luminance conversion: Y = 0.299R + 0.587G + 0.114B
    if len(img_array.shape) == 3:
        gray = (0.299 * img_array[:, :, 0] +
                0.587 * img_array[:, :, 1] +
                0.114 * img_array[:, :, 2]).astype(np.uint8)
    else:
        gray = img_array.astype(np.uint8)

    # Center crop to focus on Regions of Interest (ROI)
    h, w = gray.shape
    ch, cw = int(h * sample_info["zoom"]), int(w * sample_info["zoom"])
    sy, sx = (h - ch) // 2, (w - cw) // 2
    cropped = gray[sy:sy + ch, sx:sx + cw]

    img_pil = Image.fromarray(cropped)
    img_pil.thumbnail((target_size, target_size))
    return np.array(img_pil)

def otsu_segmentation(gray_img, invert=False):
    """Computes optimal global threshold using Otsu's variance maximization."""
    hist = np.zeros(256)
    for pixel in gray_img.flatten():
        hist[pixel] += 1

    total_px = gray_img.size
    max_var, best_thresh = 0, 0
    sum_total = sum(i * hist[i] for i in range(256))
    sum_bg, weight_bg = 0, 0

    for t in range(256):
        weight_bg += hist[t]
        if weight_bg == 0:
            continue
        weight_fg = total_px - weight_bg
        if weight_fg == 0:
            break

        sum_bg += t * hist[t]
        mean_bg = sum_bg / weight_bg
        mean_fg = (sum_total - sum_bg) / weight_fg

        var_between = weight_bg * weight_fg * ((mean_bg - mean_fg) ** 2)
        if var_between > max_var:
            max_var = var_between
            best_thresh = t

    binary = np.zeros_like(gray_img, dtype=np.uint8)
    if invert:
        binary[gray_img < best_thresh] = 1
    else:
        binary[gray_img > best_thresh] = 1

    return binary, best_thresh

def pad_image(binary_img, kh, kw):
    """Applies zero-padding to handle boundary conditions during convolution."""
    ph, pw = kh // 2, kw // 2
    h, w = binary_img.shape
    padded = np.zeros((h + 2 * ph, w + 2 * pw), dtype=np.uint8)
    padded[ph:ph + h, pw:pw + w] = binary_img
    return padded

def erosion(binary_img, kernel):
    """Morphological erosion using sliding window."""
    kh, kw = kernel.shape
    padded = pad_image(binary_img, kh, kw)
    output = np.zeros_like(binary_img)
    kernel_sum = np.sum(kernel == 1)

    for i in range(binary_img.shape[0]):
        for j in range(binary_img.shape[1]):
            if np.sum(padded[i:i + kh, j:j + kw] * kernel) == kernel_sum:
                output[i, j] = 1
    return output

def dilation(binary_img, kernel):
    """Morphological dilation using sliding window."""
    kh, kw = kernel.shape
    padded = pad_image(binary_img, kh, kw)
    output = np.zeros_like(binary_img)

    for i in range(binary_img.shape[0]):
        for j in range(binary_img.shape[1]):
            if np.sum(padded[i:i + kh, j:j + kw] * kernel) > 0:
                output[i, j] = 1
    return output

def opening(binary_img, kernel):
    """Morphological opening (erosion followed by dilation)."""
    return dilation(erosion(binary_img, kernel), kernel)

def closing(binary_img, kernel):
    """Morphological closing (dilation followed by erosion)."""
    return erosion(dilation(binary_img, kernel), kernel)

